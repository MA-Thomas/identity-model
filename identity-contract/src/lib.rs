#[cfg(test)]
mod tests {
    use super::*;
    fn intent() -> EnrollmentIntent {
        EnrollmentIntent {
            version: VERSION,
            product: "cs-mail/test".into(),
            operation: "op".into(),
            account: "1".into(),
            challenge: "c".repeat(64),
            initial_key: SigningKey::from_bytes(&[1; 32]).verifying_key().to_bytes(),
            enrollment_digest: [2; 32],
            bank_digest: [3; 32],
            created_at: 100,
            expires_at: 200,
        }
    }
    #[test]
    fn decisions_are_bound_to_all_context_and_time() {
        let i = intent();
        let d = SignedDecision::sign(
            DecisionClaims {
                issuer: "identity".into(),
                intent: i.clone(),
                subject_ref: "scoped".to_string().try_into().unwrap(),
                binding_version: 1,
                security_version: 1,
                policy: CS_MAIL_POLICY.into(),
                evidence_ref: "bank".into(),
                issued_at: 100,
                expires_at: 200,
            },
            &[4; 32],
        )
        .unwrap();
        let v = DecisionVerifier::new(
            "identity".into(),
            i.product.clone(),
            SigningKey::from_bytes(&[4; 32]).verifying_key().to_bytes(),
        )
        .unwrap();
        assert!(v.verify(&d, &i, 150).is_ok());
        for now in [99, 200] {
            assert!(v.verify(&d, &i, now).is_err());
        }
        for field in 0..5 {
            let mut other = i.clone();
            match field {
                0 => other.product = "phoros/test".into(),
                1 => other.operation = "other".into(),
                2 => other.initial_key = [7; 32],
                3 => other.bank_digest = [8; 32],
                _ => other.enrollment_digest = [9; 32],
            }
            assert!(v.verify(&d, &other, 150).is_err());
        }
        let mut tampered = d.clone();
        tampered.claims.subject_ref = "attacker".to_string().try_into().unwrap();
        assert!(v.verify(&tampered, &i, 150).is_err());
        assert!(i
            .verify_possession(&i.prove_possession(&[1; 32]).unwrap())
            .is_ok());
        assert!(i
            .verify_possession(&i.prove_possession(&[2; 32]).unwrap())
            .is_err());
    }
}
